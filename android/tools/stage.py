"""Stages the runtime sources for the Android build: python android/tools/stage.py <stage folder>

The Windows build (scripts/setup.py step_stage) lays the runtime and the lifter out in one folder; the Android build does
the same, into android/build/stage by default, plus the host-only generated headers that need no dump (as
scripts/make_release.py does). Nothing here reads a dump.
"""
import os
import shutil
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
PLAN = [('runtime', '', None), ('tools/lifter', '', None), ('fighter_sdk', 'fighter_sdk', None), ('mods', '', None)]

# sdktest_data.h is the reference data of the SDK self-test (SSBU_SDK_SELFTEST=1, off by default); the real one is made
# from suyu's sources (gen_sdktest.py). Without them: empty tables, the self-test then reports a mismatch, nothing else.
SDKTEST_STUB = '''/* placeholder written by android/tools/stage.py: no suyu sources, so the SDK self-test has no reference data */
#define MII_DEFAULT_COUNT 6
static const uint32_t mii_default_raw[6][49] = {{0}};
static const uint16_t mii_default_nick[6][10] = {{0}};
#define MII_ACCESSOR_COUNT 1
static const char *const mii_accessor_names[MII_ACCESSOR_COUNT] = {""};
static const uint8_t mii_accessor_expect[6][MII_ACCESSOR_COUNT] = {{0}};
static const struct { const char *name; const uint8_t *plain; unsigned plain_size; const uint8_t *comp; unsigned comp_size; } zvecs[] = {{"", 0, 0, 0, 0}};
static const uint8_t zvec_corrupt[1] = {0};
#define ZVEC_CORRUPT_PLAIN_SIZE 0
static const struct { const char *name; const uint8_t *data; unsigned size; const uint8_t *rgb; int width, height; } jvecs[] = {{"", 0, 0, 0, 0, 0}};
'''

STUB_LIST = ('/* no audit data: the strict-mode lists are empty (the port runs the same; SSBU_STRICT then reports nothing) */\n'
             'static const char *const %s[] = {\n    "",\n};\n')


def copy_if_changed(src, dst):
    if os.path.exists(dst) and os.path.getsize(dst) == os.path.getsize(src) and os.path.getmtime(dst) >= os.path.getmtime(src):
        return 0
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)
    return 1


def install_header(text):
    import re
    blk = re.search(r'# >>> audit block.*?# <<< audit block', text, re.S)
    names = []
    if blk:
        names = [l.strip() for l in blk.group(0).splitlines()
                 if l.strip() and not l.startswith('#') and l.split()[0] not in ('cut', 'lift', 'trap', 'addr')]
    return ('/* generated by android/tools/stage.py from the managed block of sdklift_roots.txt */\n'
            'static const char *const sdk_install_names[] = {\n' + ''.join('    "%s",\n' % n for n in names) + '};\n')


def write_if_changed(path, text):
    if os.path.exists(path) and open(path, encoding='utf-8', errors='replace').read() == text:
        return
    with open(path, 'w', newline='\n', encoding='utf-8') as f:
        f.write(text)


def main():
    stage = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, 'android', 'build', 'stage'))
    n = changed = 0
    for src, dst, ext in PLAN:
        for root, dirs, files in os.walk(os.path.join(REPO, src)):
            dirs[:] = [d for d in dirs if d != '__pycache__']
            for f in files:
                if ext and not f.endswith(ext):
                    continue
                rel = os.path.relpath(os.path.join(root, f), os.path.join(REPO, src))
                n += 1
                changed += copy_if_changed(os.path.join(root, f), os.path.join(stage, dst, rel))
    if not os.path.exists(os.path.join(stage, 'quad_tests.h')):
        subprocess.check_call([sys.executable, 'gen_quad_tests.py'], cwd=stage, stdout=subprocess.DEVNULL)
    if not os.path.exists(os.path.join(stage, 'sdktest_data.h')):
        write_if_changed(os.path.join(stage, 'sdktest_data.h'), SDKTEST_STUB)
    with open(os.path.join(REPO, 'tools', 'lifter', 'sdklift_roots.txt'), encoding='utf-8', errors='replace') as f:
        write_if_changed(os.path.join(stage, 'sdklift_install.h'), install_header(f.read()))
    for name, var in (('fake_whitelist.h', 'audit_whitelist'), ('fake_openlist.h', 'audit_openlist')):
        if not os.path.exists(os.path.join(stage, name)):
            write_if_changed(os.path.join(stage, name), STUB_LIST % var)
    print('staged %d files (%d changed) into %s' % (n, changed, stage))


if __name__ == '__main__':
    main()
